const DIALECT_KEYS = Object.keys(DIALECTS);
const DIALECT_TOTAL = Object.values(DIALECTS).reduce((a, b) => a + b, 0);

// a random dialect, as often as DIALECTS says
export function randomDialect() {
  let r = Math.random() * DIALECT_TOTAL;
  for (const k of DIALECT_KEYS) { r -= DIALECTS[k]; if (r < 0) return k; }
  return 'dhaka';
}

// every line with its code: [{ key, text, pool, dialect }]
const ALL = [];
for (const [pool, list] of Object.entries(LINES)) {
  if (Array.isArray(list)) list.forEach((text, i) => ALL.push({ key: pool + '-' + (i + 1), text, pool, dialect: null }));
  else for (const [d, sub] of Object.entries(list)) sub.forEach((text, i) => ALL.push({ key: pool + '-' + d + '-' + (i + 1), text, pool, dialect: d }));
}
const keyOf = new Map();
for (const l of ALL) if (!keyOf.has(l.text)) keyOf.set(l.text, l.key);

export const lineKey = (text) => keyOf.get(text) || null;
export const allLines = () => ALL.slice();

const pickOf = (a) => a[Math.floor(Math.random() * a.length)];
// a line from `pool` for somebody who talks `dialect` (own dialect 4 times out of 5, otherwise Dhaka)
export function pickLine(pool, dialect) {
  const list = LINES[pool];
  if (!list) return '…';
  if (Array.isArray(list)) return pickOf(list);
  const own = dialect && list[dialect] && list[dialect].length ? list[dialect] : null;
  if (own && (dialect === 'dhaka' || Math.random() < 0.8)) return pickOf(own);
  return pickOf(list.dhaka || Object.values(list)[0]);
}
