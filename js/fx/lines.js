export const lineKey = (text) => keyOf.get(text) || null;
export const pickLine = (pool) => { const a = LINES[pool]; return a[Math.floor(Math.random() * a.length)]; };
export const allLines = () => [...keyOf.entries()].map(([text, key]) => ({ key, text }));
